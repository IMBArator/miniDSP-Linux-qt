def _fake_site_packages(tmp_path: Path, files=None) -> Path:
    site = tmp_path / "site-packages"
    for rel in files if files is not None else _KEEP + _DROP + _OTHER:
        path = site / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_bytes(b"x")
    return site


def test_prune_keeps_the_allow_list_and_removes_everything_else(tmp_path):
    site = _fake_site_packages(tmp_path)
    removed = wb.prune_site_packages(site)

    for rel in _KEEP + _OTHER:
        assert (site / rel).is_file(), f"{rel} should have been kept"
    for rel in _DROP:
        assert not (site / rel).exists(), f"{rel} should have been removed"
    assert {p.name for p in removed} >= {"QtQml.pyd", "designer.exe", "pyside6-designer"}
    # Emptied directories are gone; populated ones remain.
    for gone in ("PySide6/qml", "PySide6/translations", "PySide6/plugins/sqldrivers", "shiboken6/include", "bin"):
        assert not (site / gone).exists(), gone
    assert (site / "PySide6" / "plugins" / "imageformats").is_dir()


def test_prune_refuses_an_unexpected_layout(tmp_path):
    files = [f for f in _KEEP + _DROP + _OTHER if not f.endswith("qwindows.dll")]
    site = _fake_site_packages(tmp_path, files)
    with pytest.raises(wb.BuildError, match="qwindows.dll"):
        wb.prune_site_packages(site)
    # Nothing was touched.
    assert (site / "PySide6" / "designer.exe").exists()


def test_prune_refuses_when_a_required_file_is_missing(tmp_path):
    files = [f for f in _KEEP + _DROP + _OTHER if not f.endswith("Qt6Svg.dll")]
    site = _fake_site_packages(tmp_path, files)
    with pytest.raises(wb.BuildError, match="Qt6Svg.dll"):
        wb.prune_site_packages(site)


# --- DLL closure ----------------------------------------------------------------------


def test_check_dll_closure_flags_only_removed_dependencies(tmp_path):
    app = tmp_path / "app"
    (app / "Lib").mkdir(parents=True)
    for name in ("python313.dll", "Lib/QtGui.pyd", "Lib/Qt6Gui.dll"):
        (app / name).write_bytes(b"x")
    before = {"python313.dll", "qtgui.pyd", "qt6gui.dll", "qt6network.dll", "opengl32sw.dll"}
    imports = {
        "QtGui.pyd": ["Qt6Gui.dll", "python313.dll", "KERNEL32.dll"],
        "Qt6Gui.dll": ["Qt6Network.dll", "DWrite.dll", "icuuc.dll"],
        "python313.dll": ["VCRUNTIME140.dll"],
    }
    problems = wb.check_dll_closure(app, before, imports_of=lambda p: imports[p.name])
    # Qt6Network was in the tree and is gone → flagged. System DLLs never were → ignored.
    assert problems == {"qt6gui.dll": ["Qt6Network.dll"]}


def test_check_dll_closure_passes_for_a_closed_tree(tmp_path):
    app = tmp_path / "app"
    app.mkdir()
    for name in ("a.dll", "b.dll"):
        (app / name).write_bytes(b"x")
    problems = wb.check_dll_closure(
        app, {"a.dll", "b.dll", "c.dll"}, imports_of=lambda p: ["b.dll", "user32.dll"]
    )
    assert problems == {}


# --- PE import reader -----------------------------------------------------------------


def _fake_pe(imports: list[str], delay: list[str] = ()) -> bytes:
    """Build a minimal PE32+ image with import and delay-import directories."""
    sec_rva, sec_off = 0x1000, 0x200
    blob = bytearray()

    def add(chunk: bytes) -> int:
        offset = len(blob)
        blob.extend(chunk)
        return offset

    name_rvas = [sec_rva + add(n.encode() + b"\0") for n in imports]
    delay_rvas = [sec_rva + add(n.encode() + b"\0") for n in delay]
    while len(blob) % 8:
        blob.append(0)
    import_rva = sec_rva + len(blob)
    for rva in name_rvas:
        add(struct.pack("<IIIII", 0x2000, 0, 0, rva, 0x3000))
    add(bytes(20))  # terminator
    delay_rva = sec_rva + len(blob) if delay else 0
    for rva in delay_rvas:
        add(struct.pack("<IIIIIIII", 1, rva, 0, 0, 0, 0, 0, 0))
    if delay:
        add(bytes(32))

    dos = bytearray(0x40)
    dos[:2] = b"MZ"
    struct.pack_into("<I", dos, 0x3C, 0x40)
    coff = struct.pack("<HHIIIHH", 0x8664, 1, 0, 0, 0, 240, 0x22)
    opt = bytearray(240)
    struct.pack_into("<H", opt, 0, 0x20B)  # PE32+
    struct.pack_into("<I", opt, 108, 16)  # NumberOfRvaAndSizes
    struct.pack_into("<II", opt, 112 + 1 * 8, import_rva, 20 * (len(imports) + 1))
    struct.pack_into("<II", opt, 112 + 13 * 8, delay_rva, 32 * (len(delay) + 1) if delay else 0)
    section = bytearray(40)
    section[:5] = b".data"
    struct.pack_into("<IIII", section, 8, len(blob), sec_rva, len(blob), sec_off)
    header = dos + b"PE\0\0" + coff + opt + section
    header += bytes(sec_off - len(header))
    return bytes(header) + bytes(blob)


def test_pe_imports_reads_import_and_delay_import_tables(tmp_path):
    pe = tmp_path / "fake.pyd"
    pe.write_bytes(_fake_pe(["python313.dll", "KERNEL32.dll"], ["Qt6Svg.dll"]))
    assert wb.pe_imports(pe) == ["python313.dll", "KERNEL32.dll", "Qt6Svg.dll"]


def test_pe_imports_handles_no_imports_and_non_pe_files(tmp_path):
    empty = tmp_path / "empty.dll"
    empty.write_bytes(_fake_pe([]))
    assert wb.pe_imports(empty) == []
    text = tmp_path / "notes.dll"
    text.write_bytes(b"this is not a PE file")
    assert wb.pe_imports(text) == []



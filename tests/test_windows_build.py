from pathlib import Path

import pytest

_BUILD_PY = Path(__file__).resolve().parents[1] / "packaging" / "windows" / "build.py"
_spec = importlib.util.spec_from_file_location("windows_build", _BUILD_PY)
wb = importlib.util.module_from_spec(_spec)
sys.modules["windows_build"] = wb
_spec.loader.exec_module(wb)


# --- version and naming ----------------------------------------------------------


def test_project_version_reads_pyproject(tmp_path):
    pyproject = tmp_path / "pyproject.toml"
    pyproject.write_text('[project]\nname = "x"\nversion = "1.4.2"\n')
    assert wb.project_version(pyproject) == "1.4.2"


@pytest.mark.parametrize(
    "version, expected",
    [("1.2.3", (1, 2, 3)), ("1.2.0-rc1", (1, 2, 0)), ("2.0", (2, 0, 0)), ("1.0.0+local", (1, 0, 0))],
)
def test_version_tuple_drops_prerelease_and_pads(version, expected):
    assert wb.version_tuple(version) == expected


def test_python_version_helpers():
    assert wb.short_version("3.13.15") == "3.13"
    assert wb.dll_digits("3.13.15") == "313"


def test_artifact_names():
    zip_name, setup_name, top = wb.artifact_names("1.2.0")
    assert zip_name == "minidspqt-1.2.0-win_amd64.zip"
    assert setup_name == "minidspqt-1.2.0-win_amd64-setup.exe"
    assert top == "minidspqt-1.2.0"


def test_pth_content_is_isolated_stdlib_app_dir_and_site_packages():
    text = wb.pth_content("3.13.15")
    # "." is where the embeddable distribution keeps _ctypes.pyd and friends.
    assert text.splitlines() == ["python313.zip", ".", "Lib\\site-packages"]
    assert "import site" not in text


def _fake_app_dir(tmp_path: Path) -> Path:
    app = tmp_path / "app"
    (app / "Lib" / "site-packages").mkdir(parents=True)
    for name in ("python313.zip", "python313.dll", "_ctypes.pyd", "_socket.pyd"):
        (app / name).write_bytes(b"x")
    return app


def test_check_search_path_accepts_the_generated_pth(tmp_path):
    app = _fake_app_dir(tmp_path)
    assert wb.check_search_path(app, wb.pth_content("3.13.15")) == []


def test_check_search_path_catches_a_missing_app_dir_entry(tmp_path):
    app = _fake_app_dir(tmp_path)
    problems = wb.check_search_path(app, "python313.zip\nLib\\site-packages\n")
    assert any("_ctypes.pyd" in p and "'.'" in p for p in problems)


def test_check_search_path_catches_missing_entries(tmp_path):
    app = _fake_app_dir(tmp_path)
    problems = "\n".join(wb.check_search_path(app, "python313.zip\n.\nLib\\typo\n"))
    assert "does not exist: Lib\\typo" in problems
    assert "site-packages is not on sys.path" in problems


def test_render_template_fills_and_rejects_leftovers():
    assert wb.render_template("v=@VERSION@ m=@MAJOR@", {"VERSION": "1.2.3", "MAJOR": "1"}) == "v=1.2.3 m=1"
    with pytest.raises(wb.BuildError, match="@MINOR@"):
        wb.render_template("@VERSION@ @MINOR@", {"VERSION": "1.2.3"})


# --- requirements filter (MINIDSP_LINUX_WHEEL override) ----------------------------

_EXPORT = """\
# This file was autogenerated by uv via the following command:
#    uv export --frozen --no-dev --no-emit-project --no-hashes
markdown-it-py==4.2.0
    # via rich
minidsp-linux @ https://github.com/IMBArator/miniDSP-Linux/releases/download/v1.2.0/minidsp_linux-1.2.0-py3-none-any.whl
    # via minidsp-linux-qt
pyside6-essentials==6.11.0
    # via minidsp-linux-qt
rich==15.0.0
    # via minidsp-linux
hidapi==0.15.0 ; sys_platform == 'win32'
    # via minidsp-linux
"""


def test_filter_requirements_drops_the_pin_and_its_via_comment():
    out = wb.filter_requirements(_EXPORT, "minidsp-linux")
    assert "minidsp-linux @" not in out
    assert "# via minidsp-linux-qt\n" not in out.split("pyside6")[0]
    assert "pyside6-essentials==6.11.0\n    # via minidsp-linux-qt" in out
    assert "rich==15.0.0\n    # via minidsp-linux" in out
    assert "hidapi==0.15.0 ; sys_platform == 'win32'" in out
    assert out.startswith("# This file was autogenerated")


def test_filter_requirements_normalises_names_and_ignores_unknown():
    assert "minidsp-linux @" not in wb.filter_requirements(_EXPORT, "MiniDSP_Linux")
    assert wb.filter_requirements(_EXPORT, "not-there") == _EXPORT
    # A prefix must not match: "rich" is not "rich-extra".
    assert "rich==15.0.0" in wb.filter_requirements(_EXPORT, "rich-extra")



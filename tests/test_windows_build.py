"""packaging/windows/build.py — the pure helpers of the Windows build.

Why these tests exist
---------------------
The Windows distribution is assembled on Linux and can only be *run* on a
Windows machine, so everything that can be checked without one is checked
here: the ``._pth`` search path, the requirements filter behind the
``MINIDSP_LINUX_WHEEL`` override, the PySide6 allow-list prune, the DLL
import-closure rule that guards the prune, the PE import reader that feeds
it, and the structural check the build applies to its own zip. No network,
no ``makensis``, no cross-compiler: every test runs on a fake tree.
"""

from __future__ import annotations

import importlib.util
import struct
